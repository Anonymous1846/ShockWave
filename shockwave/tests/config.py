import httpx
from typing import Dict, Any, List, Optional
from shockwave import net
from shockwave.schema.models import GraphQLSchema
from shockwave.output.sarif_writer import ShockwaveFinding

async def scan_config(
    url: str,
    schema: GraphQLSchema,
    headers: Optional[Dict[str, str]] = None
) -> List[ShockwaveFinding]:
    """
    Checks for general configuration issues on the target server.
    """
    findings = []
    req_headers = {"Content-Type": "application/json"}
    if headers:
        req_headers.update(headers)

    # Finding 1: Introspection check
    # We send the introspection query to see if it responds with schema
    introspection_query = "query { __schema { types { name } } }"
    async with net.client() as client:
        try:
            res = await client.post(url, json={"query": introspection_query}, headers=req_headers, timeout=10)
            if res.status_code == 200 and "__schema" in str(res.json()):
                findings.append(ShockwaveFinding(
                    id="",  # Generated by sarif writer if empty
                    rule_id="SHOCKWAVE-CONF-001",
                    rule_name="Introspection enabled in production",
                    severity="info",
                    owasp_category="API8:2023 — Security Misconfiguration",
                    cwe_id="CWE-16",
                    field_path="Schema",
                    engine="Generic",
                    evidence_request=f"POST {url} with query: {introspection_query}",
                    evidence_response=str(res.json())[:500],
                    auth_context="No Auth" if not headers else "Provided Auth",
                    confidence="confirmed",
                    confirmation_count=1,
                    remediation="Disable introspection in production environments (e.g. set introspection: false in Apollo Server configuration).",
                    references=["https://cheatsheetseries.owasp.org/cheatsheets/GraphQL_Cheat_Sheet.html#introspection"]
                ))
        except Exception:
            pass

        # Finding 2: Field suggestions check.
        # Engines (Graphene, Apollo, ...) only emit "Did you mean" when the
        # probed name is CLOSE to a real field, so derive a near-miss from an
        # actual schema field (drop the last char) instead of a random string.
        probe_fields = []
        q_type = schema.types.get(schema.query_type or "Query") if schema else None
        if q_type and q_type.fields:
            real = next((f.name for f in q_type.fields if len(f.name) >= 4), q_type.fields[0].name)
            # Append a char: a near-miss that is guaranteed NOT a real field
            # (dropping a char can collide with another real field, e.g.
            # "pastes" -> "paste"), so the engine emits "Did you mean <real>".
            probe_fields.append(real + "x")
        probe_fields.append("__non_existent_field_suggestion_probe")  # static fallback

        suggestion_query = f"query {{ {probe_fields[0]} }}"
        has_suggestion = False
        res_data = {}
        try:
            for pf in probe_fields:
                res = await client.post(url, json={"query": f"query {{ {pf} }}"}, headers=req_headers, timeout=10)
                res_data = res.json()
                if any("did you mean" in e.get("message", "").lower() for e in res_data.get("errors", [])):
                    has_suggestion = True
                    suggestion_query = f"query {{ {pf} }}"
                    break
            if has_suggestion:
                findings.append(ShockwaveFinding(
                    id="",
                    rule_id="SHOCKWAVE-CONF-002",
                    rule_name="Field suggestions enabled",
                    severity="info",
                    owasp_category="API8:2023 — Security Misconfiguration",
                    cwe_id="CWE-200",
                    field_path="Schema",
                    engine="Generic",
                    evidence_request=f"POST {url} with query: {suggestion_query}",
                    evidence_response=str(res_data)[:500],
                    auth_context="No Auth" if not headers else "Provided Auth",
                    confidence="confirmed",
                    confirmation_count=1,
                    remediation="Disable field suggestion error messages in production. In Apollo Server, use plugins or custom formatError to strip suggestions.",
                    references=["https://cheatsheetseries.owasp.org/cheatsheets/GraphQL_Cheat_Sheet.html#disable-suggestions"]
                ))
        except Exception:
            pass

        auth_hdr = dict(headers) if headers else {}

        def _executed(res) -> bool:
            """True only if the server actually executed the probe (returned a
            __typename value) — strict, to avoid flagging empty/echoed bodies."""
            try:
                return res.status_code == 200 and bool((res.json().get("data") or {}).get("__typename"))
            except Exception:
                return False

        # Finding 3: GET-based query execution (CSRF surface — a GET that
        # executes can be triggered cross-site without a preflight).
        try:
            res = await client.get(url, params={"query": "query{__typename}"}, headers=auth_hdr, timeout=10)
            if _executed(res):
                findings.append(ShockwaveFinding(
                    id="", rule_id="SHOCKWAVE-CONF-003",
                    rule_name="GraphQL query execution over HTTP GET",
                    severity="medium",
                    owasp_category="API8:2023 — Security Misconfiguration",
                    cwe_id="CWE-352", field_path="Schema", engine="Generic",
                    evidence_request=f"GET {url}?query=query{{__typename}}",
                    evidence_response=str(res.text)[:300],
                    auth_context="No Auth" if not headers else "Provided Auth",
                    confidence="confirmed", confirmation_count=1,
                    remediation="Reject GET for queries (or at least for mutations); require POST with a JSON content type to prevent cross-site request forgery.",
                    references=["https://cheatsheetseries.owasp.org/cheatsheets/GraphQL_Cheat_Sheet.html#csrf-prevention"]
                ))
        except Exception:
            pass

        # Finding 4: execution via a non-preflighted content type (CSRF).
        try:
            res = await client.post(
                url, content="query=query{__typename}",
                headers={**auth_hdr, "Content-Type": "application/x-www-form-urlencoded"}, timeout=10)
            if _executed(res):
                findings.append(ShockwaveFinding(
                    id="", rule_id="SHOCKWAVE-CONF-004",
                    rule_name="GraphQL accepts form-encoded body (CSRF)",
                    severity="medium",
                    owasp_category="API8:2023 — Security Misconfiguration",
                    cwe_id="CWE-352", field_path="Schema", engine="Generic",
                    evidence_request=f"POST {url} (application/x-www-form-urlencoded) body: query=query{{__typename}}",
                    evidence_response=str(res.text)[:300],
                    auth_context="No Auth" if not headers else "Provided Auth",
                    confidence="confirmed", confirmation_count=1,
                    remediation="Only accept application/json for GraphQL; a simple (non-preflighted) content type lets a cross-site form submit a request.",
                    references=["https://cheatsheetseries.owasp.org/cheatsheets/GraphQL_Cheat_Sheet.html#csrf-prevention"]
                ))
        except Exception:
            pass

        # Finding 5: directive overloading (no limit on repeated directives =
        # parser-amplification DoS vector). Flag only if the server PARSED all
        # of them (executed, or returned per-directive errors) rather than
        # rejecting with a size/complexity limit.
        try:
            overloaded = "query { __typename " + ("@skip(if: true) " * 500) + "}"
            res = await client.post(url, json={"query": overloaded}, headers=req_headers, timeout=15)
            body = res.text.lower()
            rejected = any(x in body for x in ("too many", "maximum", "limit", "complexity", "request too large"))
            try:
                errs = res.json().get("errors", []) or []
            except Exception:
                errs = []
            parsed_all = _executed(res) or (res.status_code == 200 and errs and not rejected)
            if parsed_all and not rejected:
                findings.append(ShockwaveFinding(
                    id="", rule_id="SHOCKWAVE-CONF-005",
                    rule_name="Directive overloading (no directive limit)",
                    severity="low",
                    owasp_category="API4:2023 — Unrestricted Resource Consumption",
                    cwe_id="CWE-400", field_path="Schema", engine="Generic",
                    evidence_request="query { __typename @skip(if: true) x500 }",
                    evidence_response=str(res.text)[:200],
                    auth_context="No Auth" if not headers else "Provided Auth",
                    confidence="likely", confirmation_count=1,
                    remediation="Cap the number of directives (and overall query size/complexity) accepted per request.",
                    references=["https://cheatsheetseries.owasp.org/cheatsheets/GraphQL_Cheat_Sheet.html#query-cost-analysis"]
                ))
        except Exception:
            pass

    return findings
